import { launch, shot, pickRole, preview } from '../lib.mjs';
const srv = await preview(4180);
const b = await launch();
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs = [];
p.on('pageerror', e => errs.push(String(e)));
await p.goto(srv.url);
await p.waitForFunction(() => window.__game, null, { timeout: 90000 });
await pickRole(p, { g: process.env.G || 'f' });
await p.waitForTimeout(800);
for (let i = 0; i < 6; i++) await p.mouse.wheel(0, -100);
await p.waitForTimeout(600);
await p.screenshot({ path: shot('c-idle.png') });
await p.mouse.move(900, 300);
await p.keyboard.down('KeyD');
await p.waitForTimeout(500);
await p.screenshot({ path: shot('c-walk.png') });
await p.keyboard.down('ShiftLeft');
await p.waitForTimeout(600);
await p.screenshot({ path: shot('c-run.png') });
await p.keyboard.up('ShiftLeft');
await p.keyboard.up('KeyD');
await p.evaluate(() => {
  const g = window.__game;
  const s = g.sols.find(s => s.post && s.state !== 'dead');
  if (s) g.tp(s.pos.x + 3, s.pos.z + 3);
});
await p.waitForTimeout(1200);
await p.screenshot({ path: shot('c-checkpoint.png') });
console.log(errs);
await b.close();
srv.stop();
process.exit(0);
